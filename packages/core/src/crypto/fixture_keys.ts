async function importPair(index: number): Promise<CryptoKeyPair> {
  const item = material[index]!;
  const privateKey = await crypto.subtle.importKey(
    "pkcs8",
    new Uint8Array(item.bytes),
    { name: "ECDSA", namedCurve: "P-256" },
    true,
    ["sign"],
  );
  const privateJwk = await crypto.subtle.exportKey("jwk", privateKey);
  const { d: _discard, key_ops: _ops, ...publicJwk } = privateJwk;
  const publicKey = await crypto.subtle.importKey(
    "jwk",
    { ...publicJwk, key_ops: ["verify"] },
    { name: "ECDSA", namedCurve: "P-256" },
    true,
    ["verify"],
  );
  return { privateKey, publicKey };
}
export async function fixtureDeviceSigner(which: 0 | 1): Promise<DeviceSigner> {
  const pair = await importPair(which);
  return {
    deviceId: material[which].id,
    publicJwk: () => crypto.subtle.exportKey("jwk", pair.publicKey),
    sign: async (message) =>
      new Uint8Array(
        await crypto.subtle.sign(
          { name: "ECDSA", hash: "SHA-256" },
          pair.privateKey,
          bufferSource(message),
        ),
      ),
  };
}
